class AssetDeclaration(models.Model):
    class Kind(models.TextChoices):
        START = "START", "Na początek kadencji"
        ANNUAL = "ANNUAL", "Roczne"
        END = "END", "Na koniec kadencji"

    class Status(models.TextChoices):
        PENDING = "PENDING", "Oczekuje na analizę"
        EXTRACTED = "EXTRACTED", "Przeanalizowane"
        NEEDS_REVIEW = "NEEDS_REVIEW", "Wymaga weryfikacji"
        FAILED = "FAILED", "Błąd analizy"

    mp = models.ForeignKey(MP, on_delete=models.CASCADE, related_name="declarations")
    year = models.PositiveSmallIntegerField(help_text="Year the estate is described as of")
    kind = models.CharField(max_length=8, choices=Kind.choices, default=Kind.ANNUAL)
    source_url = models.URLField(max_length=500, blank=True)
    raw = models.ForeignKey(RawDocument, null=True, blank=True, on_delete=models.SET_NULL)
    status = models.CharField(max_length=16, choices=Status.choices, default=Status.PENDING)
    extractor = models.CharField(max_length=32, blank=True)
    confidence = models.FloatField(null=True, blank=True)
    notes = models.TextField(blank=True)
    is_demo = models.BooleanField(
        default=False, help_text="Data generated by MockExtractor for demonstration"
    )
    reviewed = models.BooleanField(default=False)
    ocr_text = models.TextField(blank=True, help_text="OCR text; cached so the slow OCR does not have to run again")
    ocr_engine = models.CharField(max_length=32, blank=True)
    ocr_confidence = models.FloatField(null=True, blank=True)
    structured = models.JSONField(null=True, blank=True, help_text="Full model answer matching schema.DeclarationData")
    verification = models.JSONField(null=True, blank=True, help_text="Report of checking the answer against the OCR text")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "asset declaration"
        verbose_name_plural = "asset declarations"
        ordering = ["mp", "-year"]
        constraints = [
            models.UniqueConstraint(fields=["mp", "year", "kind"], name="uniq_declaration"),
        ]

    def __str__(self):
        return f"{self.mp} - {self.year} ({self.get_kind_display()})"

    @property
    def pdf_url(self) -> str:
        # Local copies are only served by Django in DEBUG (see config/urls.py). In production
        # link to the official source, so the link never points at a missing /media/ file.
        if settings.DEBUG and self.raw and self.raw.file:
            return self.raw.file.url
        return self.source_url

    @property
    def latest_successful_run(self):
        """Latest successful run (uses prefetch_related("runs") when present)."""
        return next((r for r in self.runs.all() if r.success), None)


class AssetItem(models.Model):
    declaration = models.ForeignKey(AssetDeclaration, on_delete=models.CASCADE, related_name="items")
    category = models.CharField(max_length=16, choices=AssetCategory.choices)
    label = models.CharField(max_length=200)
    description = models.CharField(max_length=500, blank=True)
    value = models.DecimalField(max_digits=16, decimal_places=2, null=True, blank=True)
    currency = models.CharField(max_length=3, default="PLN")
    value_pln = models.DecimalField(max_digits=16, decimal_places=2, null=True, blank=True)
    area_m2 = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True)
    ownership = models.CharField(max_length=128, blank=True)
    position = models.PositiveSmallIntegerField(default=0)

    class Meta:
        verbose_name = "declaration item"
        verbose_name_plural = "declaration items"
        ordering = ["category", "position"]

    def __str__(self):
        return self.label


class ExtractionRun(models.Model):
    declaration = models.ForeignKey(AssetDeclaration, on_delete=models.CASCADE, related_name="runs")
    extractor = models.CharField(max_length=32)
    model = models.CharField(max_length=128, blank=True)
    prompt_version = models.CharField(max_length=32, blank=True)
    success = models.BooleanField(default=False)
    confidence = models.FloatField(null=True, blank=True)
    duration_ms = models.PositiveIntegerField(default=0)
    prompt_tokens = models.PositiveIntegerField(null=True, blank=True)
    completion_tokens = models.PositiveIntegerField(null=True, blank=True)
    cost_usd = models.DecimalField(
        max_digits=12, decimal_places=8, null=True, blank=True,
        help_text="Cost of the model calls in USD, when the provider reported it",
    )
    llm_calls = models.PositiveSmallIntegerField(default=0)
    raw_output = models.JSONField(null=True, blank=True)
    error = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
        verbose_name = "extraction run"
        verbose_name_plural = "extraction runs"

    def usage_summary(self) -> str:
        """Model, cost and tokens; empty when the provider reported neither cost nor tokens."""
        if self.cost_usd is None and self.prompt_tokens is None:
            return ""
        parts = [self.model] if self.model else []
        if self.cost_usd is not None:
            text = f"{self.cost_usd:.6f}".rstrip("0").rstrip(".")
            parts.append(text.replace(".", ",") + " USD")
        if self.prompt_tokens is not None:
            parts.append(f"{self.prompt_tokens} tokenów wejścia + {self.completion_tokens or 0} wyjścia")
        if self.llm_calls > 1:
            parts.append(f"{self.llm_calls} wywołania modelu")
        return " · ".join(parts)
